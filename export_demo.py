"""Write docs/weights.js: the two DQN networks (training seed 0 of each) used by the web demo."""
import base64
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parent
saved = torch.load(ROOT / "models" / "dqn_weights.pt", weights_only=True)
lines = ["// Generated by export_demo.py: layer weights as base64 little-endian float32 (rows = outputs)", "const DQN_WEIGHTS = {"]
for key, name in (("calm", "calm DQN 0"), ("robust", "robust DQN 0")):
    state = saved[name]["state"]
    parts = [f'"{base64.b64encode(state[f"{i}.{p}"].numpy().astype("<f4").tobytes()).decode()}"'
             for i in (0, 2, 4) for p in ("weight", "bias")]
    lines.append(f"  {key}: [{', '.join(parts)}],")
lines.append("};")
lines.append('if (typeof module !== "undefined") module.exports = DQN_WEIGHTS;')
(ROOT / "docs" / "weights.js").write_text("\n".join(lines) + "\n")
